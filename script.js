let currentQuestion = 0;
let score = 0;

const progress = document.getElementById("progress");
const question = document.getElementById("question");
const choices = document.getElementById("choices");
const result = document.getElementById("result");
const nextButton = document.getElementById("nextButton");
const quiz = document.getElementById("quiz");
const scoreScreen = document.getElementById("scoreScreen");
const scoreText = document.getElementById("score");
const restartButton = document.getElementById("restartButton");

function showQuestion() {
  const q = questions[currentQuestion];

  progress.textContent =
    `${currentQuestion + 1} / ${questions.length}`;

  question.textContent = q.question;

  choices.innerHTML = "";
  result.innerHTML = "";
  nextButton.classList.add("hidden");

  // 選択肢をランダムに並べ替える
  const shuffledChoices = q.choices
    .map((choice, index) => ({
      choice: choice,
      originalIndex: index
    }))
    .sort(() => Math.random() - 0.5);

  shuffledChoices.forEach(item => {
    const button = document.createElement("button");

    button.textContent = item.choice;
    button.className = "choice";

    button.addEventListener("click", () => {
      selectAnswer(item.originalIndex);
    });

    choices.appendChild(button);
  });
}

function selectAnswer(selectedIndex) {
  const q = questions[currentQuestion];
  const buttons = document.querySelectorAll(".choice");

  buttons.forEach(button => {
    button.disabled = true;
  });

  if (selectedIndex === q.answer) {
    score++;
    buttons[selectedIndex].classList.add("correct");

    result.innerHTML =
      `<strong>正解！</strong><br>${q.explanation}`;
  } else {
    buttons[selectedIndex].classList.add("wrong");
    buttons[q.answer].classList.add("correct");

    result.innerHTML =
      `<strong>不正解！</strong><br>` +
      `正解は「${String.fromCharCode(65 + q.answer)}」です。<br>` +
      `${q.explanation}`;
  }

  nextButton.classList.remove("hidden");
}

nextButton.addEventListener("click", () => {
  currentQuestion++;

  if (currentQuestion < questions.length) {
    showQuestion();
  } else {
    showScore();
  }
});

function showScore() {
  quiz.classList.add("hidden");
  scoreScreen.classList.remove("hidden");

  const percentage =
    Math.round((score / questions.length) * 100);

  scoreText.textContent =
    `${questions.length}問中 ${score}問正解！ ${percentage}点`;
}

restartButton.addEventListener("click", () => {
  currentQuestion = 0;
  score = 0;

  quiz.classList.remove("hidden");
  scoreScreen.classList.add("hidden");

  showQuestion();
});

showQuestion();
